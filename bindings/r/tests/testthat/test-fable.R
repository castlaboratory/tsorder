test_that("TSORDER() plugs into the fable workflow", {
  skip_if_not_installed("fabletools")
  skip_if_not_installed("tsibble")
  skip_if_not_installed("distributional")
  set.seed(4)
  y <- as.numeric(arima.sim(list(ar = c(1.2, -0.6)), 300))
  df <- tsibble::tsibble(idx = seq_along(y), value = y, index = idx)
  mbl <- fabletools::model(df, fit = TSORDER(value, method = "pacf"))
  expect_s3_class(mbl, "mdl_df")
  expect_match(format(mbl$fit[[1]]), "TSORDER\\(2,0,0\\)")
  fc <- fabletools::forecast(mbl, h = 5)
  expect_s3_class(fc, "fbl_ts")
  expect_equal(nrow(fc), 5L)
  expect_true(all(is.finite(fc$.mean)))
  gl <- fabletools::glance(mbl)
  expect_true(all(c("sigma2", "AIC") %in% names(gl)))
  aug <- fabletools::augment(mbl)
  expect_true(all(is.finite(aug$.fitted)))
})
