"""Cross-language golden tests: replay the fixed series through every
selector against the numbers the Rust core produced (fixture
regenerated by `cargo run --example golden`; the R package checks the
same file). On the platform that generated the fixture the match is
bit-exact; across platforms, libm transcendentals (atan/sin/exp inside
the Jacobi SVD and Imhof) differ by ulps, so floats are compared at a
1e-9 relative tolerance."""

import json
import math
import pathlib

import tsorder

GOLD = json.loads((pathlib.Path(__file__).parent / "golden.json").read_text())


def same(a, b):
    if isinstance(a, list):
        assert len(a) == len(b)
        for u, v in zip(a, b):
            same(u, v)
    elif isinstance(a, float):
        ok = math.isfinite(b) and (
            a == b or abs(a - b) <= 1e-9 * max(abs(a), abs(b), 1e-300)
        )
        assert ok, f"{a!r} != {b!r}"
    else:
        assert a == b


def test_ic_order():
    r = tsorder.ic_order(GOLD["series"], criterion="bic")
    assert r["order"] == GOLD["ic_bic"]["order"]
    same(GOLD["ic_bic"]["values"], r["values"])


def test_fh_order():
    r = tsorder.fh_order(GOLD["series"])
    g = GOLD["fh_pacf"]
    assert (r["order"], r["p_n"]) == (g["order"], g["p_n"])
    same(g["tau"], r["tau"])
    same(g["studentized"], r["studentized"])


def test_mcmillan_routes():
    svc = tsorder.svc_order(GOLD["series"])
    assert svc["order"] == GOLD["svc"]["order"]
    same(GOLD["svc"]["correlations"], svc["correlations"])

    rank = tsorder.hankel_rank_order(GOLD["series"])
    assert rank["order"] == GOLD["hankel_rank"]["order"]
    same(GOLD["hankel_rank"]["pvalues"], rank["pvalues"])

    svt = tsorder.hankel_svt_order(GOLD["series"])
    assert svt["order"] == GOLD["hankel_svt"]["order"]
    same(GOLD["hankel_svt"]["xi"], svt["xi"])
    same(GOLD["hankel_svt"]["singular_values"], svt["singular_values"])


def test_arma_identification():
    ea = tsorder.eacf(GOLD["series"])
    g = GOLD["eacf"]
    order = ea["order"] if ea["order"] is not None else (-1, -1)
    assert tuple(order) == (g["p"], g["q"])
    same(g["row0"], ea["table"][0])

    hr = tsorder.hannan_rissanen(GOLD["series"])
    g = GOLD["hr"]
    assert (hr["p"], hr["q"]) == (g["p"], g["q"])
    same(g["phi"], hr["phi"])
    same(g["theta"], hr["theta"])
    same(g["sigma2"], hr["sigma2"])


def test_integration_and_robust():
    integ = tsorder.integration_order(GOLD["rw"])
    assert integ["d"] == GOLD["integration"]["d"]
    same(GOLD["integration"]["stats"], integ["stats"])
    same(GOLD["qn"], tsorder.qn(GOLD["short"]))
    same(GOLD["robust_acf"], tsorder.robust_acf(GOLD["series"], 5))


def test_numpy_input_and_errors():
    import numpy as np

    x = np.asarray(GOLD["series"])
    assert tsorder.fh_order(x)["order"] == GOLD["fh_pacf"]["order"]
    try:
        tsorder.fh_order([1.0, 2.0, 3.0])
        raise AssertionError("expected ValueError")
    except ValueError as e:
        assert "short" in str(e)
